const menuButton = document.querySelector('.menu-button');
const nav = document.querySelector('.main-nav');

document.querySelectorAll('[data-track]').forEach((element) => {
  element.addEventListener('click', () => window.trackSiteEvent?.(element.dataset.track));
});

menuButton?.addEventListener('click', () => {
  const open = nav.classList.toggle('open');
  menuButton.setAttribute('aria-expanded', String(open));
});

nav?.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => {
  nav.classList.remove('open');
  menuButton?.setAttribute('aria-expanded', 'false');
}));

const observer = new IntersectionObserver((entries) => entries.forEach((entry) => {
  if (entry.isIntersecting) {
    entry.target.classList.add('visible');
    observer.unobserve(entry.target);
  }
}), { threshold: .12 });

document.querySelectorAll('.reveal').forEach((element) => observer.observe(element));

const credentialsDialog = document.querySelector('#credentials');
document.querySelector('[data-open="credentials"]')?.addEventListener('click', () => credentialsDialog.showModal());

