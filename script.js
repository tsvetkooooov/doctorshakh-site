const guideDialog = document.querySelector('#guide-dialog');
document.querySelectorAll('.guide-details').forEach((button) => button.addEventListener('click', () => {
  const guide = guides[button.dataset.guide];
  if (!guide) return;
  guideDialog.querySelector('#guide-dialog-meta').textContent = guide.meta;
  guideDialog.querySelector('#guide-dialog-title').textContent = guide.title;
  guideDialog.querySelector('#guide-dialog-lead').textContent = guide.lead;
  guideDialog.querySelector('#guide-dialog-for').innerHTML = guide.for.map((item) => `<li>${item}</li>`).join('');
  guideDialog.querySelector('#guide-dialog-list').innerHTML = guide.items.map((item) => `<li>${item}</li>`).join('');
  guideDialog.querySelector('#guide-dialog-result').textContent = guide.result;
  guideDialog.querySelector('#guide-dialog-buy').href = guide.url;
  guideDialog.showModal();
}));

const reviewTrack = document.querySelector('#review-track');
const scrollReviews = (direction) => {
  if (!reviewTrack) return;
  const card = reviewTrack.querySelector('.review-card');
  reviewTrack.scrollBy({ left: direction * ((card?.offsetWidth || 340) + 18), behavior: 'smooth' });
};
document.querySelector('[data-review-prev]')?.addEventListener('click', () => scrollReviews(-1));
document.querySelector('[data-review-next]')?.addEventListener('click', () => scrollReviews(1));

document.querySelectorAll('dialog').forEach((dialog) => {
  dialog.querySelector('.dialog-close')?.addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', (event) => {
    if (event.target === dialog) dialog.close();
  });
});
